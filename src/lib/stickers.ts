/** CSS effect names — same emoji always maps to the same effect for every user. */
export const STICKER_EFFECTS = ['bounce', 'spin', 'pulse', 'shake', 'glow', 'float', 'heartbeat', 'wiggle', 'tada', 'jelly', 'flip', 'zoom', 'swing', 'rubber', 'flash', 'drift'] as const;
export type StickerEffect = (typeof STICKER_EFFECTS)[number];

export function stickerEffectForKey(key: string): StickerEffect {
  let h = 0;
  for (let i = 0; i < key.length; i++) {
    h = (Math.imul(31, h) + key.charCodeAt(i)) >>> 0;
  }
  return STICKER_EFFECTS[h % 16]!;
}

export function stickerEffectClass(key: string): string {
  return `xup-sticker-fx-${stickerEffectForKey(key)}`;
}

